def main():
    if not SRC.exists():
        print(f"ERROR: {SRC} not found", file=sys.stderr)
        sys.exit(1)

    with SRC.open("r", encoding="utf-8") as f:
        data = json.load(f)

    before = len(data)
    added = 0
    for msg_key, by_type in NEW.items():
        for type_id in TYPES:
            full_key = f"{type_id}_{msg_key}"
            if full_key in data:
                print(f"SKIP (exists): {full_key}")
                continue
            data[full_key] = by_type[type_id]
            added += 1

    with SRC.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"OK: before={before} after={len(data)} added={added}")

if __name__ == "__main__":
    main()
